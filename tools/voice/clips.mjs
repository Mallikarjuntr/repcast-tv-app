#!/usr/bin/env node
// After the Polly recordings are unpacked into apps/tv/assets/voice/<id>.mp3, writes
// apps/tv/src/voiceClips.ts so the app bundles exactly those files (Metro needs static requires).
//
//   node tools/voice/clips.mjs
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const tv = join(here, '..', '..', 'apps', 'tv');
const phrases = JSON.parse(readFileSync(join(here, 'phrases.json'), 'utf8'));

const found = phrases.filter((p) => existsSync(join(tv, 'assets', 'voice', `${p.id}.mp3`)));
const missing = phrases.filter((p) => !found.includes(p));
const body = found.map((p) => `  '${p.id}': require('../assets/voice/${p.id}.mp3'),`).join('\n');
writeFileSync(
  join(tv, 'src', 'voiceClips.ts'),
  `// Generated by tools/voice/clips.mjs from assets/voice/*.mp3 — do not edit by hand.\nexport const CLIPS: Record<string, number> = {\n${body}\n};\n`,
);
console.log(`${found.length} clips bundled${missing.length ? `; missing ${missing.length}: ${missing.map((p) => p.text).join(' | ')}` : ''}`);
